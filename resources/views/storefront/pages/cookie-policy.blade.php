
			
			<p><strong>Cookie Policy</strong></p>

<p><strong>1. What are Cookies?</strong></p>

<p>Cookies are small text files stored on your device (computer, mobile, or tablet) when you visit our website www.example.com (the “Website”). They are used to ensure the proper operation of the Website, enhance your user experience, analyze site usage, and deliver personalized services or advertisements.</p>

<hr>

<p><strong>2. Types of Cookies We Use</strong></p>

<p><strong>2.1 Strictly Necessary Cookies</strong></p>

<p>These cookies are essential for the functioning of the Website, your navigation, security, and access to basic features such as shopping cart and login. Without them, certain services will not be available.</p>

<p><strong>2.2 Performance and Analytics Cookies</strong></p>

<p>We use cookies to collect anonymous statistics about the use and performance of the Website through tools such as Google Analytics. This information helps us improve our services, products, and user experience.</p>

<p><strong>2.3 Preference Cookies</strong></p>

<p>These store information about your preferences, such as language selection, product display, or region.</p>

<p><strong>2.4 Advertising/Third-Party Cookies</strong></p>

<p>These are used to display personalized ads and analyze the effectiveness of marketing campaigns. They may be placed by us or by advertising partners/third parties such as social media networks.</p>

<hr>

<p><strong>3. Third-Party Cookies</strong></p>

<p>Some cookies are managed by third parties (such as Google Analytics or advertising/analytics platforms). These cookies are governed by their own privacy policies, and we do not control them.</p>

<hr>

<p><strong>4. How We Use Cookies</strong></p>

<p>We use cookies to:</p>

<ul>
	<li>Ensure the secure and efficient operation of the Website</li>
	<li>Remember your preferences</li>
	<li>Analyze the use and performance of the Website</li>
	<li>Facilitate registration, purchase, and payment of products/services</li>
	<li>Deliver relevant advertising content</li>
</ul>

<hr>

<p><strong>5. Consent &amp; Cookie Management</strong></p>

<p>Upon your first visit to the Website, a banner (cookie notice) will appear, allowing you to accept or set your preferences for non-strictly necessary cookies. You may change your settings or withdraw your consent at any time via your browser settings or relevant tools on the Website.</p>

<p>Disabling certain cookies may affect the functionality or availability of some services.</p>

