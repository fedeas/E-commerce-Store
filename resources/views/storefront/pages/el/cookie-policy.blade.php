<p><strong>Πολιτική Cookies</strong></p>

<p><strong>1. Τι είναι τα Cookies;</strong></p>
<p>Τα cookies είναι μικρά αρχεία κειμένου που αποθηκεύονται στη συσκευή σας όταν επισκέπτεστε το www.example.com. Χρησιμοποιούνται για τη σωστή λειτουργία του website, τη βελτίωση της εμπειρίας χρήστη, την ανάλυση χρήσης και την παροχή εξατομικευμένων υπηρεσιών ή διαφημίσεων.</p>

<hr>
<p><strong>2. Τύποι Cookies που χρησιμοποιούμε</strong></p>
<p><strong>2.1 Απολύτως απαραίτητα cookies</strong></p>
<p>Είναι απαραίτητα για τη λειτουργία του website, την πλοήγηση, την ασφάλεια και βασικές λειτουργίες όπως το καλάθι και η σύνδεση.</p>
<p><strong>2.2 Cookies απόδοσης και analytics</strong></p>
<p>Συλλέγουν ανώνυμα στατιστικά χρήσης και απόδοσης, π.χ. μέσω Google Analytics, ώστε να βελτιώνουμε τις υπηρεσίες και την εμπειρία χρήστη.</p>
<p><strong>2.3 Cookies προτιμήσεων</strong></p>
<p>Αποθηκεύουν επιλογές όπως γλώσσα, εμφάνιση προϊόντων ή περιοχή.</p>
<p><strong>2.4 Διαφημιστικά / τρίτων cookies</strong></p>
<p>Χρησιμοποιούνται για προσωποποιημένες διαφημίσεις και μέτρηση απόδοσης καμπανιών. Μπορεί να τοποθετούνται από εμάς ή από συνεργάτες όπως social media και advertising networks.</p>

<hr>
<p><strong>3. Cookies τρίτων</strong></p>
<p>Ορισμένα cookies διαχειρίζονται τρίτοι πάροχοι. Αυτά υπόκεινται στις δικές τους πολιτικές απορρήτου και δεν τα ελέγχουμε απευθείας.</p>

<hr>
<p><strong>4. Πώς χρησιμοποιούμε τα Cookies</strong></p>
<ul>
    <li>Για ασφαλή και αποτελεσματική λειτουργία του website.</li>
    <li>Για να θυμόμαστε τις προτιμήσεις σας.</li>
    <li>Για ανάλυση χρήσης και απόδοσης.</li>
    <li>Για διευκόλυνση εγγραφής, αγοράς και πληρωμής.</li>
    <li>Για σχετικό διαφημιστικό περιεχόμενο.</li>
</ul>

<hr>
<p><strong>5. Συγκατάθεση και διαχείριση Cookies</strong></p>
<p>Κατά την πρώτη επίσκεψη εμφανίζεται σχετικό banner όπου μπορείτε να αποδεχθείτε ή να ρυθμίσετε μη απαραίτητα cookies. Μπορείτε να αλλάξετε ή να αποσύρετε τη συγκατάθεσή σας από τις ρυθμίσεις browser ή από τα διαθέσιμα εργαλεία του website.</p>
<p>Η απενεργοποίηση ορισμένων cookies μπορεί να επηρεάσει τη λειτουργικότητα κάποιων υπηρεσιών.</p>

<hr>
<p><strong>6. Ενδεικτικά Cookies</strong></p>
<ul>
    <li><strong>ga, gid:</strong> ανώνυμη ανάλυση επισκεψιμότητας.</li>
    <li><strong>cookie_consent:</strong> αποθήκευση επιλογής συγκατάθεσης.</li>
    <li><strong>session_id:</strong> διαχείριση σύνδεσης και session.</li>
    <li><strong>language:</strong> αποθήκευση προτιμώμενης γλώσσας.</li>
</ul>
<p>Για ενημερωμένη λίστα μπορείτε να επικοινωνήσετε μαζί μας ή να δείτε τα cookie settings του website.</p>

<hr>
<p><strong>7. Διάρκεια διατήρησης</strong></p>
<p>Κάθε cookie έχει διαφορετική διάρκεια. Κάποια διαγράφονται όταν κλείνετε τον browser, ενώ άλλα παραμένουν για συγκεκριμένο χρονικό διάστημα ή μέχρι να τα διαγράψετε.</p>

