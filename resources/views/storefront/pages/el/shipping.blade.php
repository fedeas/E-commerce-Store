<h3>4. Κόστη αποστολής</h3>
<ul>
    <li>Τα έξοδα αποστολής υπολογίζονται στο checkout ανάλογα με την επιλογή παράδοσης.</li>
    <li>Κατά περιόδους μπορεί να προσφέρονται δωρεάν αποστολές, μόνο όταν αναφέρεται ξεκάθαρα.</li>
    <li>Αν παραγγελία με δωρεάν αποστολή επιστραφεί για λόγο που δεν αφορά ελάττωμα ή λάθος προϊόν, μπορεί να αφαιρεθεί το πραγματικό κόστος αποστολής από την επιστροφή χρημάτων.</li>
</ul>

