<h3>6. Παράδοση και κίνδυνος απώλειας</h3>
<ul>
    <li>Οι παραδόσεις γίνονται στη διεύθυνση ή στο σημείο παραλαβής που δηλώνετε στο checkout.</li>
    <li>Ο κίνδυνος απώλειας και η κυριότητα περνούν σε εσάς με την παράδοση ή παραλαβή.</li>
    <li>Αν δέμα επιστραφεί λόγω λάθος στοιχείων ή μη παραλαβής, τα νέα έξοδα αποστολής βαρύνουν εσάς.</li>
</ul>

